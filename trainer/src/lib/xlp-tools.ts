/** Какой инструмент предложить после задачи тренажёра — по тексту подсказки про XLPlain. */
export function toolForTip(text: string): string | null {
  const t = (text || '').toLowerCase();
  if (/дубл/.test(t)) return 'dubli';
  if (/сверк|сверить|сверя/.test(t)) return 'sverka';
  if (/очистк|пробел|телефон|фио|регистр/.test(t)) return 'ochistka';
  if (/объедин|сопостав/.test(t)) return 'obedinenie';
  return null;
}
